// LQ-C: Monte Carlo prediction from three episodes: first-visit and every-visit estimates, ordinary and weighted importance
// sampling for off-policy evaluation, and a step-by-step TD(0) run on the first episode for comparison.
// Lectures 4 (Monte Carlo methods) and 5 (TD learning).
import type { Rng } from '../../../../lib/rng'
import type { LQGenerator, LQInstance } from '../../../../lib/types'
import { dec, tex, tol3 } from '../../../shared/format'

export interface Params {
  g10: number // discount in tenths
  e1: number[] // rewards of episode 1: states A, B, A
  e2: number[] // episode 2: states B, A
  e3: number[] // episode 3: states A, A, B
  pi: number[][] // target-policy probabilities (percent) of the taken actions, 3 episodes x 2 steps
  b: number[][] // behaviour-policy probabilities (percent) of the taken actions
  g: number[] // returns of the three off-policy episodes
}

export function sample(rng: Rng): Params {
  const rew = (k: number) => Array.from({ length: k }, () => rng.int(-2, 6))
  const ep = () => [rng.pick([50, 80, 100]), rng.pick([50, 80, 100])]
  const bb = () => [rng.pick([25, 40, 50, 80]), rng.pick([25, 40, 50, 80])]
  return {
    g10: rng.pick([5, 9]),
    e1: rew(3), e2: rew(2), e3: rew(3),
    pi: [ep(), ep(), ep()], b: [bb(), bb(), bb()],
    g: [rng.int(1, 9), rng.int(1, 9), rng.int(1, 9)],
  }
}

export function build(P: Params): LQInstance {
  const gam = P.g10 / 10
  const [a1, a2, a3] = P.e1, [, b2] = P.e2, [c1, c2, c3] = P.e3
  const G1_0 = a1 + gam * a2 + gam ** 2 * a3
  const G1_2 = a3
  const G2_1 = b2
  const G3_0 = c1 + gam * c2 + gam ** 2 * c3
  const G3_1 = c2 + gam * c3
  const fv = (G1_0 + G2_1 + G3_0) / 3
  const ev = (G1_0 + G1_2 + G2_1 + G3_0 + G3_1) / 5
  const rho = P.pi.map((pi, i) => (pi[0] / P.b[i][0]) * (pi[1] / P.b[i][1]))
  const ordinary = rho.reduce((s, r, i) => s + r * P.g[i], 0) / 3
  const weighted = rho.reduce((s, r, i) => s + r * P.g[i], 0) / rho.reduce((s, r) => s + r, 0)

  // TD(0) with alpha = 0.5 through episode 1, step by step
  const vA1 = 0.5 * a1
  const d2 = a2 + gam * vA1
  const vB2 = 0.5 * d2
  const d3 = a3 - vA1
  const tdA = vA1 + 0.5 * d3

  const f = (x: number) => dec(x)
  const probs = (i: number) => tex(f(P.pi[i][0] / 100) + ',\\ ' + f(P.pi[i][1] / 100)) + ' under ' + tex('\\pi') + ' and ' + tex(f(P.b[i][0] / 100) + ',\\ ' + f(P.b[i][1] / 100)) + ' under ' + tex('b')

  return {
    intro: 'Three episodes of a two-state chain are observed with discount ' + tex('\\gamma=' + dec(gam)) + '. Each step lists the state and the reward received on leaving it. Episode 1: ' + tex('A') + ' (' + a1 + '), ' + tex('B') + ' (' + a2 + '), ' + tex('A') + ' (' + a3 + '), end. Episode 2: ' + tex('B') + ' (' + P.e2[0] + '), ' + tex('A') + ' (' + b2 + '), end. Episode 3: ' + tex('A') + ' (' + c1 + '), ' + tex('A') + ' (' + c2 + '), ' + tex('B') + ' (' + c3 + '), end. Give all answers to 3 decimal places.',
    parts: [
      {
        prompt: 'Find the first-visit Monte Carlo estimate of ' + tex('V(A)') + ' from the three episodes.',
        answer: fv, tolerance: tol3, lecture: 4,
        explanation: 'First visits to ' + tex('A') + ' give the returns ' + tex(dec(G1_0)) + ' (episode 1: ' + tex(a1 + '+' + dec(gam) + '\\times' + a2 + '+' + dec(gam ** 2) + '\\times' + a3) + '), ' + tex(dec(G2_1)) + ' (episode 2) and ' + tex(dec(G3_0)) + ' (episode 3). Their average is ' + tex(dec(fv)) + '.',
      },
      {
        prompt: 'Find the every-visit Monte Carlo estimate of ' + tex('V(A)') + ' from the same three episodes.',
        answer: ev, tolerance: tol3, lecture: 4,
        explanation: 'Every visit counts: episode 1 gives ' + tex(dec(G1_0)) + ' and ' + tex(dec(G1_2)) + ', episode 2 gives ' + tex(dec(G2_1)) + ', episode 3 gives ' + tex(dec(G3_0)) + ' and ' + tex(dec(G3_1)) + '. The average of the five returns is ' + tex(dec(ev)) + '.',
      },
      {
        prompt: 'Now evaluate a target policy ' + tex('\\pi') + ' from episodes generated by a behaviour policy ' + tex('b') + '. Three episodes of two steps start in the same state and have returns ' + tex(P.g.join(',\\ ')) + '. The probabilities of the two actions actually taken are: episode 1: ' + probs(0) + '; episode 2: ' + probs(1) + '; episode 3: ' + probs(2) + '. Find the ordinary importance-sampling estimate of the start-state value.',
        answer: ordinary, tolerance: tol3, lecture: 4,
        explanation: 'The ratios ' + tex('\\rho=\\prod\\pi/b') + ' are ' + tex(rho.map(f).join(',\\ ')) + '. Ordinary importance sampling averages ' + tex('\\rho G') + ': ' + tex('(' + rho.map((r, i) => f(r) + '\\times' + P.g[i]).join('+') + ')/3=' + dec(ordinary)) + '.',
      },
      {
        prompt: 'For the same three episodes, find the weighted importance-sampling estimate of the start-state value.',
        answer: weighted, tolerance: tol3, lecture: 4,
        explanation: 'Weighted importance sampling divides ' + tex('\\sum\\rho G') + ' by ' + tex('\\sum\\rho') + ': ' + tex('\\frac{' + dec(rho.reduce((s, r, i) => s + r * P.g[i], 0)) + '}{' + dec(rho.reduce((s, r) => s + r, 0)) + '}=' + dec(weighted)) + '.',
      },
      {
        prompt: 'For comparison, run TD(0) with step size ' + tex('\\alpha=0.5') + ' through episode 1 only, updating after every step in order, starting from ' + tex('V(A)=V(B)=0') + ' (the last step ends the episode, with terminal value 0). What is ' + tex('V(A)') + ' at the end?',
        answer: tdA, tolerance: tol3, lecture: 5,
        explanation: 'Step 1 (' + tex('A\\to B') + '): ' + tex('\\delta=' + a1 + ',\\ V(A)=' + dec(vA1)) + '. Step 2 (' + tex('B\\to A') + '): ' + tex('\\delta=' + a2 + '+' + dec(gam) + '\\times' + dec(vA1) + '=' + dec(d2) + ',\\ V(B)=' + dec(vB2)) + '. Step 3 (' + tex('A') + ' to the end): ' + tex('\\delta=' + a3 + '-' + dec(vA1) + '=' + dec(d3) + ',\\ V(A)=' + dec(vA1) + '+0.5\\times' + dec(d3) + '=' + dec(tdA)) + '.',
      },
    ],
  }
}

export const genC: LQGenerator = { id: 'rl-lq-c-montecarlo', generate: (rng) => build(sample(rng)) }
