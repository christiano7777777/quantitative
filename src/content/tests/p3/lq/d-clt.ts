// LQ-D: CLT approximation for a binomial, a conditional expectation on a partition, and a fair-walk exit probability.
// Lectures 9 (CLT), 10 (conditional expectation), 11 (martingales / optional stopping).
import type { Rng } from '../../../../lib/rng'
import type { LQGenerator, LQInstance } from '../../../../lib/types'
import { dec, normalCdf, tex, tol3, tol4 } from '../../../shared/format'

export interface Params {
  n: number // number of trials
  pNum: number // success probability = pNum / 10
  dx: number // x = round(n p) + dx
  w: number[] // weights of Omega = {1..6}, summing to 20
  block: number[] // block of each outcome
  k: number
  jBlock: number // block whose conditional mean is asked
  N: number // walk target
  i: number // walk start
}

export function sample(rng: Rng): Params {
  const n = rng.pick([36, 49, 64, 100, 144])
  const pNum = rng.pick([3, 4, 6, 7])
  const dx = rng.pick([-6, -5, -4, -3, -2, 2, 3, 4, 5, 6])
  const cuts = rng.sample(Array.from({ length: 19 }, (_, i) => i + 1), 5).sort((a, b) => a - b)
  const w = [cuts[0], cuts[1] - cuts[0], cuts[2] - cuts[1], cuts[3] - cuts[2], cuts[4] - cuts[3], 20 - cuts[4]]
  const k = rng.pick([2, 3])
  const order = rng.shuffle([0, 1, 2, 3, 4, 5])
  const block = new Array<number>(6).fill(0)
  order.forEach((o, idx) => { block[o] = idx < k ? idx : rng.int(0, k - 1) })
  const N = rng.pick([8, 10, 12, 15, 20])
  let i: number
  do i = rng.int(2, N - 2)
  while (2 * i === N)
  return { n, pNum, dx, w, block, k, jBlock: rng.int(0, k - 1), N, i }
}

export function build({ n, pNum, dx, w, block, k, jBlock, N, i }: Params): LQInstance {
  const p = pNum / 10
  const mu = n * p, sd = Math.sqrt(n * p * (1 - p))
  const x = Math.round(mu) + dx
  const z = (x - mu) / sd
  const approx = normalCdf(z)

  const blocks = Array.from({ length: k }, (_, j) => [1, 2, 3, 4, 5, 6].filter((o) => block[o - 1] === j))
  const mass = (b: number[]) => b.reduce((s, o) => s + w[o - 1], 0)
  const cond = blocks.map((b) => b.reduce((s, o) => s + o * w[o - 1], 0) / mass(b))
  const residual = [1, 2, 3, 4, 5, 6].reduce((s, o) => s + (w[o - 1] / 20) * (o - cond[block[o - 1]]) ** 2, 0)
  const walk = i / N

  const setText = (b: number[]) => '\\{' + b.join(',') + '\\}'
  return {
    intro: 'Give decimal answers to 3 decimal places unless told otherwise.',
    parts: [
      {
        prompt: tex('S_{' + n + '}\\sim\\mathrm{Bin}(' + n + ',' + dec(p) + ')') + ' is a sum of ' + n + ' i.i.d. Bernoulli variables. The central limit theorem standardises ' + tex('S_n') + ' to ' + tex('(S_n-np)/\\sqrt{np(1-p)}') + '. What is the standardised value ' + tex('z') + ' of ' + tex('x=' + x) + '? (No continuity correction.)',
        answer: z, tolerance: tol3, lecture: 9,
        explanation: tex('np=' + dec(mu)) + ' and ' + tex('\\sqrt{np(1-p)}=' + dec(sd)) + ', so ' + tex('z=(' + x + '-' + dec(mu) + ')/' + dec(sd)) + ' = ' + dec(z) + '.',
      },
      {
        prompt: 'Use the normal approximation (no continuity correction) to estimate ' + tex('P(S_{' + n + '}\\le' + x + ')') + '.',
        answer: approx, tolerance: tol3, lecture: 9,
        explanation: tex('P(S_n\\le x)\\approx\\Phi(z)=\\Phi(' + dec(z) + ')') + ' = ' + dec(approx) + '.',
      },
      {
        prompt: 'On ' + tex('\\Omega=\\{1,\\dots,6\\}') + ' let ' + tex('P(\\{i\\})=w_i/20') + ' with ' + tex('(w_1,\\dots,w_6)=(' + w.join(',') + ')') + ' and ' + tex('X(\\omega)=\\omega') +
          '. Let ' + tex('\\mathcal G') + ' be generated by the partition ' + blocks.map((b, j) => tex('B_{' + (j + 1) + '}=' + setText(b))).join(', ') + '. What is the value of ' + tex('E[X\\mid\\mathcal G]') + ' on ' + tex('B_{' + (jBlock + 1) + '}') + '?',
        answer: cond[jBlock], tolerance: tol3, lecture: 10,
        explanation: 'On an atom, ' + tex('E[X\\mid\\mathcal G]=E[X1_B]/P(B)') + '. Here ' + tex('=\\dfrac{' + blocks[jBlock].map((o) => o + '\\cdot' + w[o - 1]).join('+') + '}{' + mass(blocks[jBlock]) + '}') + ' = ' + dec(cond[jBlock]) + '.',
      },
      {
        prompt: 'In the same setting, find ' + tex('E\\big[(X-E[X\\mid\\mathcal G])^2\\big]') + ', the mean-square error of the best ' + tex('\\mathcal G') + '-measurable predictor of ' + tex('X') + '.',
        answer: residual, tolerance: tol3, lecture: 10,
        explanation: 'Compute ' + tex('E[X\\mid\\mathcal G]') + ' on each block (' + cond.map(dec).join(', ') + '), then average the squared residuals ' + tex('(\\omega-E[X\\mid\\mathcal G](\\omega))^2') + ' with weights ' + tex('w_\\omega/20') + ': ' + dec(residual) + '.',
      },
      {
        prompt: 'A fair ' + tex('\\pm1') + ' random walk starts at ' + tex(i) + ' and stops when it first hits ' + tex(0) + ' or ' + tex(N) + '. By optional stopping applied to the martingale ' + tex('S_n') + ', what is the probability it hits ' + tex(N) + ' first?',
        answer: walk, tolerance: tol4, lecture: 11,
        explanation: tex('S_{n\\wedge T}') + ' is a bounded martingale, so ' + tex('E[S_T]=i') + ', i.e. ' + tex('N\\cdot P(\\text{hit }N)=' + i) + ' and the probability is ' + tex(i + '/' + N) + ' = ' + dec(walk) + '.',
      },
    ],
  }
}

export const genD: LQGenerator = { id: 'p3-lq-d-clt', generate: (rng) => build(sample(rng)) }
